#!/usr/bin/env python3
"""Generate the Stage 7 section of docs/EVIDENCE_INDEX.md from graph sidecars.

Reads every <graph>.sources.txt written by host/plots/plot_results.py and
emits one table row per graph: graph -> CSV path -> raw-log directory ->
commit hash. Output goes either to a separate file (--out) or into an index
file (--index) strictly between the stage7 markers; text outside the
markers is never changed, and if the markers are absent the section is
appended at the end.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "<!-- stage7:begin -->"
END = "<!-- stage7:end -->"


def parse_sidecar(path):
    """Return {key: [values]} from 'key: value' lines."""
    fields = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if ": " not in line:
            continue
        key, value = line.split(": ", 1)
        fields.setdefault(key.strip(), []).append(value.strip())
    return fields


def _relative(path):
    try:
        return str(Path(path).resolve().relative_to(ROOT))
    except ValueError:
        return str(path)


def build_section(plots_dir):
    sidecars = sorted(Path(plots_dir).glob("*.sources.txt"))
    lines = [
        BEGIN,
        "## Stage 7 graphs",
        "",
        "Generated by `tools/index_evidence.py` from the `.sources.txt` sidecars "
        "in `{}`. Do not edit between the markers by hand.".format(_relative(plots_dir)),
        "",
        "| Graph | CSV | Raw log directory | Commit hash | Rows used |",
        "|---|---|---|---|---|",
    ]
    for sidecar in sidecars:
        fields = parse_sidecar(sidecar)
        graph = sidecar.parent / fields.get("graph", [sidecar.name])[0]
        lines.append("| `{}` | {} | {} | {} | {} |".format(
            _relative(graph),
            "<br>".join("`{}`".format(p) for p in fields.get("input_csv", [])) or "missing",
            "<br>".join("`{}`".format(d) for d in fields.get("rawlog_dir", [])) or "none",
            "<br>".join("`{}`".format(c) for c in fields.get("commit_hash", [])) or "none",
            fields.get("rows_used", ["?"])[0]))
    if not sidecars:
        lines.append("| | | | | no .sources.txt sidecars found |")
    lines.append(END)
    return "\n".join(lines) + "\n"


def merge_section(existing, section):
    """Replace the marked section in existing text, or append it."""
    begin = existing.find(BEGIN)
    end = existing.find(END)
    if begin != -1 and end != -1 and end > begin:
        tail = existing[end + len(END):]
        if tail.startswith("\n"):
            tail = tail[1:]
        return existing[:begin] + section + tail
    if begin != -1 or end != -1:
        raise SystemExit("index has only one stage7 marker or they are out of "
                         "order; fix it by hand first")
    separator = "" if existing.endswith("\n\n") else ("\n" if existing.endswith("\n") else "\n\n")
    return existing + separator + section


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--plots-dir", default=str(ROOT / "host" / "plots"))
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--out", help="write only the section to this file")
    target.add_argument("--index", help="update this index between the stage7 markers "
                                        "(e.g. docs/EVIDENCE_INDEX.md)")
    args = parser.parse_args(argv)

    section = build_section(args.plots_dir)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(section, encoding="utf-8")
        print("Wrote {}".format(args.out))
        return
    index = Path(args.index)
    existing = index.read_text(encoding="utf-8")
    index.write_text(merge_section(existing, section), encoding="utf-8")
    print("Updated {} between {} and {}".format(index, BEGIN, END))


if __name__ == "__main__":
    main()
